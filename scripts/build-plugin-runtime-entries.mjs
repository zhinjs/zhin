import { readFile, readdir, stat, unlink, writeFile } from 'node:fs/promises';
import { extname, join, relative, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import ts from 'typescript';

const GENERATED_MARKER = '// Generated by build-plugin-runtime-entries.mjs. Do not edit.\n';
const CAPABILITY_DIRECTORIES = [
  'adapters',
  'commands',
  'components',
  'mcp',
  'middlewares',
  'pages',
  'tools',
];
const TYPESCRIPT_EXTENSIONS = new Set(['.ts', '.tsx', '.mts', '.cts']);

export async function buildPluginRuntimeEntries(packageRoot = process.cwd()) {
  const root = resolve(packageRoot);
  const manifest = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'));
  if (manifest.zhin?.type !== 'plugin') return [];

  const sources = [];
  const pluginSource = join(root, 'plugin.ts');
  if (await isFile(pluginSource)) sources.push(pluginSource);
  for (const directory of CAPABILITY_DIRECTORIES) {
    await collectTypeScript(join(root, directory), sources);
  }

  const outputs = [];
  for (const source of sources) {
    const output = outputPath(source);
    const input = await readFile(source, 'utf8');
    const transpiled = ts.transpileModule(input, {
      fileName: source,
      compilerOptions: {
        module: ts.ModuleKind.ESNext,
        target: ts.ScriptTarget.ES2022,
        jsx: ts.JsxEmit.ReactJSX,
        verbatimModuleSyntax: true,
      },
      transformers: {
        before: [rewriteSourceImports()],
      },
      reportDiagnostics: true,
    });
    const errors = transpiled.diagnostics?.filter(
      (diagnostic) => diagnostic.category === ts.DiagnosticCategory.Error,
    ) ?? [];
    if (errors.length > 0) {
      const detail = ts.formatDiagnosticsWithColorAndContext(errors, {
        getCanonicalFileName: (file) => file,
        getCurrentDirectory: () => root,
        getNewLine: () => '\n',
      });
      throw new Error(`Cannot build ${relative(root, source)}:\n${detail}`);
    }
    await writeFile(output, `${GENERATED_MARKER}${transpiled.outputText}`, 'utf8');
    outputs.push(output);
  }
  return outputs;
}

export async function cleanPluginRuntimeEntries(packageRoot = process.cwd()) {
  const root = resolve(packageRoot);
  const candidates = [join(root, 'plugin.js')];
  for (const directory of CAPABILITY_DIRECTORIES) {
    await collectJavaScript(join(root, directory), candidates);
  }
  for (const candidate of candidates) {
    if (!await isFile(candidate)) continue;
    const content = await readFile(candidate, 'utf8');
    if (content.startsWith(GENERATED_MARKER)) await unlink(candidate);
  }
}

function rewriteSourceImports() {
  return (context) => {
    const rewrite = (literal) => {
      const value = literal.text;
      if (!value.startsWith('.')) return literal;
      const next = value.replace(/(^|\/)src\//u, '$1lib/');
      return next === value ? literal : context.factory.createStringLiteral(next);
    };
    const visit = (node) => {
      if (ts.isImportDeclaration(node) && ts.isStringLiteral(node.moduleSpecifier)) {
        return context.factory.updateImportDeclaration(
          node,
          node.modifiers,
          node.importClause,
          rewrite(node.moduleSpecifier),
          node.attributes,
        );
      }
      if (ts.isExportDeclaration(node) && node.moduleSpecifier
        && ts.isStringLiteral(node.moduleSpecifier)) {
        return context.factory.updateExportDeclaration(
          node,
          node.modifiers,
          node.isTypeOnly,
          node.exportClause,
          rewrite(node.moduleSpecifier),
          node.attributes,
        );
      }
      if (ts.isCallExpression(node)
        && node.expression.kind === ts.SyntaxKind.ImportKeyword
        && node.arguments.length === 1
        && ts.isStringLiteral(node.arguments[0])) {
        return context.factory.updateCallExpression(
          node,
          node.expression,
          node.typeArguments,
          [rewrite(node.arguments[0])],
        );
      }
      return ts.visitEachChild(node, visit, context);
    };
    return (sourceFile) => ts.visitNode(sourceFile, visit);
  };
}

async function collectTypeScript(directory, result) {
  for (const entry of await safeReadDirectory(directory)) {
    const source = join(directory, entry.name);
    if (entry.isDirectory()) await collectTypeScript(source, result);
    else if (entry.isFile()
      && TYPESCRIPT_EXTENSIONS.has(extname(entry.name))
      && !entry.name.endsWith('.d.ts')) {
      result.push(source);
    }
  }
}

async function collectJavaScript(directory, result) {
  for (const entry of await safeReadDirectory(directory)) {
    const source = join(directory, entry.name);
    if (entry.isDirectory()) await collectJavaScript(source, result);
    else if (entry.isFile() && ['.js', '.mjs', '.cjs'].includes(extname(entry.name))) {
      result.push(source);
    }
  }
}

function outputPath(source) {
  const extension = extname(source);
  const outputExtension = extension === '.mts'
    ? '.mjs'
    : extension === '.cts' ? '.cjs' : '.js';
  return `${source.slice(0, -extension.length)}${outputExtension}`;
}

async function safeReadDirectory(directory) {
  try {
    return await readdir(directory, { withFileTypes: true });
  } catch (error) {
    if (error instanceof Error && 'code' in error && error.code === 'ENOENT') return [];
    throw error;
  }
}

async function isFile(file) {
  try {
    return (await stat(file)).isFile();
  } catch {
    return false;
  }
}

const invokedPath = process.argv[1] ? pathToFileURL(resolve(process.argv[1])).href : '';
if (import.meta.url === invokedPath) {
  const root = process.argv[2] ?? process.cwd();
  await cleanPluginRuntimeEntries(root);
  const outputs = await buildPluginRuntimeEntries(root);
  process.stdout.write(`Built ${outputs.length} Plugin Runtime JS entries.\n`);
}
