/**
 * The allowed-value lists derived from tokens/tokens.mjs (ADR 0063 D17). One derivation shared by
 * the generator (which writes it as scale.json), the stylelint plugin, the ESLint plugin,
 * `zhin plugin check` and the Playwright layout audit, so they can never disagree.
 *
 * Published as `@zhin.js/console-ui/scale` (this module) and `@zhin.js/console-ui/scale.json`.
 */
import * as tokens from './tokens.mjs';

/** CSS variable prefix of every Console token. */
export const PREFIX = '--console-';

/** Tier-1 short names → CSS variable names (`space-3` → `--console-space-3`). */
export function tierOneVariable(name) {
  if (/^space-[1-8]$/u.test(name)) return `${PREFIX}${name}`;
  const radius = /^r-(\d|full)$/u.exec(name);
  if (radius) return `${PREFIX}radius-${radius[1]}`;
  const elevation = /^e-(\d)$/u.exec(name);
  if (elevation) return `${PREFIX}elevation-${elevation[1]}`;
  if (name === 'hairline' || name === 'focus') return `${PREFIX}border-${name}`;
  return null;
}

/** Replaces tier-1 short names inside a semantic value by `var(--console-…)`. */
export function resolveSemanticValue(value) {
  return value.replace(/\b(?:space-[1-8]|r-(?:\d|full)|e-\d|hairline|focus)\b/gu, (name) => `var(${tierOneVariable(name)})`);
}

const remOf = (key) => (key === '0' ? '0rem' : `${Number(key) * 0.25}rem`);

/** Base-tier variables (name → value), light theme. */
export function baseTierVariables() {
  const out = {};
  for (const [name, { size, leading }] of Object.entries(tokens.text)) {
    out[`text-${name}`] = size;
    out[`leading-${name}`] = leading;
  }
  for (const [name, value] of Object.entries(tokens.weight)) out[`weight-${name}`] = value;
  for (const [name, { value }] of Object.entries(tokens.space)) out[name] = value;
  for (const [name, value] of Object.entries(tokens.radius)) out[`radius-${name.slice(2)}`] = value;
  for (const [name, value] of Object.entries(tokens.border)) out[`border-${name}`] = value;
  for (const [name, value] of Object.entries(tokens.elevation.light)) out[`elevation-${name.slice(2)}`] = value;
  for (const [name, value] of Object.entries(tokens.breakpoints)) out[`bp-${name}`] = value;
  for (const [name, value] of Object.entries(tokens.contentWidth)) out[`content-${name}`] = value;
  out['touch-target'] = tokens.touchTarget;
  Object.assign(out, tokens.misc, tokens.deprecated);
  return out;
}

/** Media query params allowed in the shell (D16, D20): the breakpoints, both directions, plus user preferences. */
export function allowedMediaParams() {
  const params = [];
  for (const value of Object.values(tokens.breakpoints)) {
    params.push(`(min-width: ${value})`, `(width >= ${value})`, `(width < ${value})`);
  }
  params.push(
    '(prefers-reduced-motion: reduce)',
    '(prefers-reduced-motion: no-preference)',
    '(prefers-color-scheme: dark)',
    '(prefers-color-scheme: light)',
    '(prefers-contrast: more)',
    '(forced-colors: active)',
    '(hover: hover)',
    '(pointer: coarse)',
    'print',
  );
  return params;
}

/** `@custom-media` names generated for the shell. */
export function customMedia() {
  const out = {};
  for (const [name, value] of Object.entries(tokens.breakpoints)) {
    out[`--console-${name}`] = `(min-width: ${value})`;
    out[`--console-below-${name}`] = `(width < ${value})`;
  }
  return out;
}

/** Container query ranges used by the generated by-size rules. */
export function containerRanges() {
  const { sm, lg } = tokens.breakpoints;
  return {
    base: `(width < ${sm})`,
    sm: `(${sm} <= width < ${lg})`,
    lg: `(width >= ${lg})`,
  };
}

export function buildScale() {
  const semanticNames = Object.keys(tokens.semantic);
  const radiusSemantic = semanticNames.filter((name) => tokens.semantic[name].kind === 'radius');
  const elevationSemantic = semanticNames.filter((name) => tokens.semantic[name].kind === 'elevation');
  return {
    $comment: 'Generated from @zhin.js/console-ui tokens/tokens.mjs by tokens/generate.mjs (ADR 0063 D17). Do not edit.',
    breakpoints: tokens.breakpoints,
    text: Object.fromEntries(Object.entries(tokens.text).map(([name, { size }]) => [name, size])),
    weight: tokens.weight,
    space: tokens.space,
    radius: tokens.radius,
    border: tokens.border,
    elevation: Object.keys(tokens.elevation.light),
    contentWidth: tokens.contentWidth,
    touchTarget: tokens.touchTarget,
    semantic: tokens.semantic,
    tailwind: {
      /** `p-*`, `m-*`, `gap-*`, `space-*`: only these keys (D17). */
      spacingKeys: ['0', 'px', ...Object.values(tokens.space).map((entry) => entry.tailwind)],
      /** `w-*`, `h-*`, `size-*`, `inset-*`, `min-*`, `max-*`, `translate-*`, `basis-*`. */
      sizingKeys: [...tokens.sizingKeys, ...Object.keys(tokens.semanticSizes)],
      radiusKeys: ['none', '0', '1', '2', '3', '4', 'full', ...radiusSemantic.map((name) => name.replace(/-radius$/u, ''))],
      shadowKeys: ['none', 'e1', 'e2', 'e3', ...elevationSemantic.map((name) => name.replace(/-elevation$/u, ''))],
      textKeys: Object.keys(tokens.text),
      fontWeightKeys: Object.keys(tokens.weight),
      breakpointKeys: Object.keys(tokens.breakpoints),
      borderWidthKeys: ['0', 'px', 'hairline', 'focus'],
    },
    css: {
      baseTokens: Object.keys(baseTierVariables()).map((name) => `${PREFIX}${name}`),
      semanticTokens: [...semanticNames, ...Object.keys(tokens.composite)].map((name) => `${PREFIX}${name}`),
      aliasTokens: [...Object.keys(tokens.aliases).map((name) => `${PREFIX}${name}`), ...Object.keys(tokens.bareAliases)],
      customMedia: customMedia(),
      mediaParams: allowedMediaParams(),
      containerParams: [...new Set([...Object.values(containerRanges()), ...Object.values(tokens.breakpoints).flatMap((value) => [`(min-width: ${value})`, `(width >= ${value})`, `(width < ${value})`])])],
    },
  };
}

/** Sizing key → value for the Tailwind theme. */
export function sizingValues() {
  return Object.fromEntries([
    ...tokens.sizingKeys.map((key) => [key, remOf(key)]),
    ...Object.entries(tokens.semanticSizes),
  ]);
}

export { tokens };
